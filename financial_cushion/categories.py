"""Нормализация категорий Сбера к бизнес-группам финансовой подушки.

Сбер размечает операции своей категорией («Супермаркеты», «Перевод СБП»,
«Оплата по QR–коду СБП», «Прочие операции» и т.д.), но:
  - QR-операции не несут смысловой категории (проезд? магазин? подписка?);
  - скрытые услуги часто «прячутся» в переводах и «Прочих операциях»
    (например, «3801 Regular Charge: July», YANDEX*RUNCHARGE).

Поэтому классификация двухступенчатая: сначала ключевые слова в описании,
затем категория Сбера. Порядок правил важен: транспортные ключевые слова
проверяются раньше супермаркетов и т.п.
"""
from __future__ import annotations

import re

# Названия «канонических» групп вывода
SUPERMARKETS = "супермаркеты/продукты"
TRANSPORT = "Транспорт"
SUBSCRIPTIONS = "Абонементы и подписки"
UTILITIES = "жкх"
BARBER = "парикмахерские"
LOAN = "ипотека/кредит"
RESTAURANTS = "Рестораны и кафе"
HEALTH = "Здоровье и красота"
CLOTHES = "Одежда и аксессуары"
TRANSFERS = "Переводы"
CASH = "Наличные (снятие)"
SAVINGS = "Накопления (вклады)"
CARD_FEE = "Обслуживание карты"
MANDATORY_DEDUCTION = "Взыскания (обязательные)"
OTHER = "Прочие расходы"

# Категории, которые считаются транзитными/небазовыми и по умолчанию
# НЕ включаются в подушку (решение по ним принимает пользователь)
TRANSIT_CATEGORIES = {TRANSFERS, CASH, SAVINGS}

# Правила классификации: (целевая группа, regex по нижнему регистру
# «описание + категория Сбера»). Проверяются сверху вниз.
RULES: list[tuple[str, str]] = [
    # Переводы на собственный вклад/накопительный счёт — не расход
    (SAVINGS, r"karta-?vklad|карта-?вклад|пополнение вклада|открытие вклада"),
    # Ежемесячная комиссия Сбера за обслуживание карты (не «подписка»)
    (CARD_FEE, r"regular charge|комиссия за обслуживание"),
    # Обязательные списания по решению суда/ФССП
    (MANDATORY_DEDUCTION, r"взыскание|фссп|судебн"),
    # Регулярные списания-подписки (в т.ч. «Regular Charge» Сбера)
    (
        SUBSCRIPTIONS,
        r"подписк|regular charge|runcharge|steam|netflix|кинопоиск|"
        r"телеграм|telegram|нейросет|openai|chat ?gpt|spotify|"
        r"музыка|сберпрайм|яндекс плюс|абонемент",
    ),
    # Кредиты и ипотека
    (LOAN, r"ипотек|платеж по кред|погашение кредита|кредитн|рассрочк"),
    # ЖКХ
    (
        UTILITIES,
        r"жкх|квартплат|коммунал|управляющ|гбук|еирц|домклик|"
        r"электроэн|энергосбыт|водоот|водоснаб|теплоэн|капремонт|"
        r"газоснаб|гис ?жкх|интернет|роутер|мтс|билайн|мегафон|теле2",
    ),
    # Транспорт: такси, общественный транспорт, проездные
    (
        TRANSPORT,
        r"транспорт|проезд|спопат|такси|yandex\.?taxi|метро\b|"
        r"трамвай|автобус|электричк|россельхоз.*перевоз|тпп\b",
    ),
    # Парикмахерские / салоны
    (BARBER, r"барбер|парикмах|салон крас|маникюр|педикюр|массаж|стрижк"),
    # Продукты
    (
        SUPERMARKETS,
        r"супермаркет|пятёрочка|pyaterochka|magnit|магнит|монетка|"
        r"krasnoe|красное|лента|lenta|okey|окей|ашан|перекрёсток|"
        r"продукт|магазин|market\b|fix-price|фермер",
    ),
    (RESTAURANTS, r"ресторан|кафе|burger|фастфуд|кофейн|пицц|суши|доставка"),
    (HEALTH, r"аптек|apteka|клиник|стоматолог|медиц|анализы|больниц"),
    (CLOTHES, r"одежд|обув|wilda|ozon|wildberries|lamoda|маркет|алиэкспресс"),
]

# Соответствие «категория Сбера -> группа» для случаев, когда описание
# не содержит ключевых слов (проверяется после RULES)
RAW_CATEGORY_MAP: dict[str, str] = {
    "супермаркеты": SUPERMARKETS,
    "транспорт": TRANSPORT,
    "рестораны и кафе": RESTAURANTS,
    "здоровье и красота": HEALTH,
    "одежда и аксессуары": CLOTHES,
    "перевод с карты": TRANSFERS,
    "перевод сбп": TRANSFERS,
    "выдача наличных": CASH,
    "внесение наличных": CASH,
}


def classify(category: str, description: str) -> str:
    """Определяет бизнес-группу расхода по категории Сбера и описанию.

    Args:
        category: категория из шапки операции (например, «Перевод СБП»).
        description: описание операции (мерчант, ФИО, назначение платежа).

    Returns:
        Название канонической группы.
    """
    text = f"{description} {category}".lower()

    # Переводы физлицам/в другие банки выделяем по описанию в первую
    # очередь: их дальнейшую судьбу решает анализ регулярности.
    if re.match(r"перевод (для|в)\b", text):
        return TRANSFERS

    for target, pattern in RULES:
        if re.search(pattern, text):
            return target

    return RAW_CATEGORY_MAP.get(category.strip().lower(), category.strip() or OTHER)


def description_for_group(group: str) -> str:
    """Краткое пояснение, что входит в группу (для итогового отчёта)."""
    return {
        SUPERMARKETS: "продукты и бытовые покупки",
        TRANSPORT: "такси, проезд на общественном транспорте",
        SUBSCRIPTIONS: "абонементы в зал, киносервисы, телеграм, нейросети",
        UTILITIES: "коммунальные платежи, связь, интернет",
        BARBER: "стрижка, салоны красоты",
        LOAN: "платежи по кредитам и ипотеке",
        RESTAURANTS: "кафе и рестораны",
        HEALTH: "аптеки, медицина",
        CLOTHES: "одежда и аксессуары",
        MANDATORY_DEDUCTION: "судебные взыскания",
        TRANSFERS: "переводы физлицам и в другие банки",
        CASH: "снятие наличных",
        SAVINGS: "переводы на вклад/накопительный счёт (не расход)",
        CARD_FEE: "ежемесячная комиссия банка за обслуживание карты",
    }.get(group, group.lower())
